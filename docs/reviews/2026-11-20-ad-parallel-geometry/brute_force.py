"""Brute-force checks of AD parallel laws at the multirelation level.

A program maps each initial state s to an up-closed family U(s) of sets
ac' (the demon offers ac', the angel picks a state in it), as in
utp_ades_ops: x := e is e(s) in ac', demonic choice is union of families,
angelic choice is intersection, P ;;A Q is P(s, {y | Q(y, ac')}).
Only the started, terminating part is modelled (no ok flags).
Families are bitmasks over subsets; subsets are bitmasks over states.
"""
import itertools, random, sys

random.seed(1)

def subsets(n):
    return range(1 << n)

def upclose(fam, n):
    out = 0
    for X in subsets(n):
        if fam >> X & 1:
            for Z in subsets(n):
                if Z & X == X:
                    out |= 1 << Z
    return out

def members(fam, n):
    return [X for X in subsets(n) if fam >> X & 1]

def all_upsets(n):
    res = set()
    for fam in range(1 << (1 << n)):
        if upclose(fam, n) == fam:
            res.add(fam)
    return sorted(res)

def blocker(fam, n):
    out = 0
    mem = members(fam, n)
    for G in subsets(n):
        if all(X & G for X in mem):
            out |= 1 << G
    return out

# ---------- programs on a state space of size n ----------
def seq(P, Q, n):
    out = []
    for s in range(n):
        fam = 0
        for Z in subsets(n):
            ys = 0
            for y in range(n):
                if Q[y] >> Z & 1:
                    ys |= 1 << y
            if P[s] >> ys & 1:
                fam |= 1 << Z
        out.append(fam)
    return tuple(out)

def par(P, Q, n, j):
    """j(s, a, b) -> set (bitmask) of merged states; AD lifting:
    ac' must contain, for each pair, at least one merge result."""
    out = []
    for s in range(n):
        fam = 0
        for X in members(P[s], n):
            for Y in members(Q[s], n):
                pairs = [(a, b) for a in range(n) if X >> a & 1
                                 for b in range(n) if Y >> b & 1]
                for Z in subsets(n):
                    if all(j(s, a, b) & Z for a, b in pairs):
                        fam |= 1 << Z
        out.append(fam)
    return tuple(out)

def dual(P, n):
    return tuple(blocker(f, n) for f in P)

def blind(P, Q, n, j):
    return dual(par(dual(P, n), dual(Q, n), n, j), n)

def dem(P, Q):  # demonic choice
    return tuple(a | b for a, b in zip(P, Q))

def ang(P, Q):  # angelic choice
    return tuple(a & b for a, b in zip(P, Q))

def refines(P, Q):  # P ⊑ Q  iff  Q ⇒ P
    return all(q & ~p == 0 for p, q in zip(P, Q))

def nonabort(fam):
    return not (fam & 1)  # empty set not offered

# ---------- frame-disjoint setting: S = S1 x S2, |S1| = |S2| = 2 ----------
n1 = 2
N = n1 * n1
def st(x1, x2): return x1 * n1 + x2
def x1of(s): return s // n1
def x2of(s): return s % n1

comp_upsets = [f for f in all_upsets(n1) if nonabort(f) and f]  # feasible, non-aborting

def lift_left(p):   # p: tuple over x1 of families over S1
    out = []
    for s in range(N):
        fam = 0
        for X1 in members(p[x1of(s)], n1):
            X = 0
            for a in range(n1):
                if X1 >> a & 1:
                    X |= 1 << st(a, x2of(s))
            fam |= 1 << X
        out.append(upclose(fam, N))
    return tuple(out)

def lift_right(q):
    out = []
    for s in range(N):
        fam = 0
        for X2 in members(q[x2of(s)], n1):
            X = 0
            for b in range(n1):
                if X2 >> b & 1:
                    X |= 1 << st(x1of(s), b)
            fam |= 1 << X
        out.append(upclose(fam, N))
    return tuple(out)

def j_frame(s, a, b):  # left owns x1, right owns x2
    return 1 << st(x1of(a), x2of(b))

comp_progs = list(itertools.product(comp_upsets, repeat=n1))
L = [lift_left(p) for p in comp_progs]
R = [lift_right(q) for q in comp_progs]

def is_A2(fam, n):   # generated by singletons (and maybe the empty set)
    gen = 0
    for X in members(fam, n):
        if X == 0 or (X & (X - 1)) == 0:
            gen |= 1 << X
    return upclose(gen, n) == fam

def is_principal(fam, n):  # pure angelic: one minimal offered set
    mins = [X for X in members(fam, n)
            if not any(Y != X and Y & X == Y for Y in members(fam, n))]
    return len(mins) == 1

def report(name, ok, cex=None):
    print(f"{'PASS' if ok else 'FAIL'}  {name}" + (f"   counterexample: {cex}" if cex else ""))

# 1. sandwich: blind ⊑ P;Q ⊑ P∥Q and blind ⊑ Q;P ⊑ P∥Q
ok1 = True; strict_seq = None; strict_blind = None
eqA2 = True; eq_dem_first = True; eq_ang_last = True
for P in L:
    for Q in R:
        pq = par(P, Q, N, j_frame); b = blind(P, Q, N, j_frame)
        s1 = seq(P, Q, N); s2 = seq(Q, P, N)
        if not (refines(b, s1) and refines(s1, pq) and refines(b, s2) and refines(s2, pq)):
            ok1 = False
        if strict_seq is None and not refines(pq, s1) and not refines(pq, s2):
            strict_seq = (P, Q)
        if strict_blind is None and not refines(s1, b) and not refines(s2, b):
            strict_blind = (P, Q)
        pA2 = all(is_A2(f, N) for f in P); qA2 = all(is_A2(f, N) for f in Q)
        if pA2 and qA2 and not (b == pq == s1 == s2):
            eqA2 = False
        if pA2 and pq != s1:
            eq_dem_first = False
        if all(is_principal(f, N) for f in P) and pq != s2:
            eq_ang_last = False
report("blind ⊑ P;Q ⊑ P∥Q  and  blind ⊑ Q;P ⊑ P∥Q  (frame-disjoint)", ok1)
report("  ...strict: P∥Q strictly above both sequentialisations for some P,Q", strict_seq is not None)
report("  ...strict: blind strictly below both sequentialisations for some P,Q", strict_blind is not None)
report("all four coincide when both operands are A2 (pure demonic)", eqA2)
report("P∥Q = P;Q when P is A2 (demonic branch runs first)", eq_dem_first)
report("P∥Q = Q;P when P is purely angelic (angelic branch runs last)", eq_ang_last)

# 2. choice distribution (frame-disjoint, all operand triples)
ok_dem = True; ok_ang = True; strict_ang = None; eq_ang_principal = True
for P, P2 in itertools.product(L, repeat=2):
    for Q in R:
        if par(dem(P, P2), Q, N, j_frame) != dem(par(P, Q, N, j_frame), par(P2, Q, N, j_frame)):
            ok_dem = False
        lhs = ang(par(P, Q, N, j_frame), par(P2, Q, N, j_frame))
        rhs = par(ang(P, P2), Q, N, j_frame)
        if not refines(lhs, rhs):
            ok_ang = False
        if lhs != rhs:
            if strict_ang is None: strict_ang = (P, P2, Q)
            if all(is_principal(f, N) for f in Q): eq_ang_principal = False
report("(P ⊓ P')∥Q = (P∥Q) ⊓ (P'∥Q)", ok_dem)
report("(P∥Q) ⊔ (P'∥Q) ⊑ (P ⊔ P')∥Q", ok_ang)
report("  ...strict for some P,P',Q", strict_ang is not None)
report("  ...equality when Q is purely angelic", eq_ang_principal)

# 3. exchange law, random sample
ok_ex = True; strict_ex = None; rev_fail = None
for _ in range(20000):
    P, P2 = random.choice(L), random.choice(L)
    Q, Q2 = random.choice(R), random.choice(R)
    lhs = seq(par(P, Q, N, j_frame), par(P2, Q2, N, j_frame), N)
    rhs = par(seq(P, P2, N), seq(Q, Q2, N), N, j_frame)
    if not refines(lhs, rhs): ok_ex = False
    if lhs != rhs and strict_ex is None: strict_ex = (P, Q, P2, Q2)
report("(P∥Q);(P'∥Q') ⊑ (P;P')∥(Q;Q')  (frame-disjoint, 20000 samples)", ok_ex)
report("  ...strict for some sample", strict_ex is not None)

# 4. general j on a 3-state space: demonic distribution, angelic one-way, either-merge
n = 3
ups = [f for f in all_upsets(n) if nonabort(f) and f]
progs = list(itertools.product(ups, repeat=n))
ok_dem_g = True; ok_ang_g = True; ok_either = True
for _ in range(1500):
    jt = {(s, a, b): random.randrange(1, 1 << n) for s in range(n) for a in range(n) for b in range(n)}
    jf = lambda s, a, b: jt[(s, a, b)]
    P, P2, Q = random.choice(progs), random.choice(progs), random.choice(progs)
    if par(dem(P, P2), Q, n, jf) != dem(par(P, Q, n, jf), par(P2, Q, n, jf)): ok_dem_g = False
    if not refines(ang(par(P, Q, n, jf), par(P2, Q, n, jf)), par(ang(P, P2), Q, n, jf)): ok_ang_g = False
    either = lambda s, a, b: (1 << a) | (1 << b)
    if par(P, Q, n, either) != dem(P, Q): ok_either = False
report("general relational j: demonic distribution exact (1500 samples)", ok_dem_g)
report("general relational j: angelic distribution one-way (1500 samples)", ok_ang_g)
report("j(s,a,b) = {a,b} (demon keeps either branch): P∥Q = P ⊓ Q", ok_either)

# 5. duality / bottleneck minimax / Lovász (Choquet) extension
ok_bn = True
for _ in range(3000):
    U = random.choice(ups)
    G = blocker(U, n)
    beta = [random.random() for _ in range(n)]
    minmax = min(max(beta[x] for x in range(n) if X >> x & 1) for X in members(U, n))
    maxmin = max(min(beta[x] for x in range(n) if X >> x & 1) for X in members(G, n) if X)
    order = sorted(range(n), key=lambda x: beta[x])
    choquet, prev = 0.0, 0.0
    for i, x in enumerate(order):
        A = 0
        for y in order[i:]: A |= 1 << y
        choquet += (beta[x] - prev) * (G >> A & 1)
        prev = beta[x]
    if not (abs(minmax - maxmin) < 1e-12 and abs(minmax - choquet) < 1e-12): ok_bn = False
report("min_{X∈U} max_X β = max_{G∈b(U)} min_G β = Choquet/Lovász ext. (3000 samples)", ok_bn)
ok_bb = all(blocker(blocker(f, n), n) == f for f in all_upsets(n))
report("b(b(U)) = U for every up-set U (duality is an involution)", ok_bb)

# print the small witnesses in readable form
def show_fam(fam, n, name):
    mins = [X for X in members(fam, n) if not any(Y != X and Y & X == Y for Y in members(fam, n))]
    def nm(s): return f"({x1of(s)},{x2of(s)})"
    return "↑{" + ", ".join("{" + ",".join(nm(s) for s in range(n) if X >> s & 1) + "}" for X in mins) + "}"
if strict_seq:
    P, Q = strict_seq
    print("\nstrict sandwich witness at s=(0,0):")
    for nmf, f in [("P", P[0]), ("Q", Q[0]), ("P∥Q", par(P, Q, N, j_frame)[0]),
                   ("P;Q", seq(P, Q, N)[0]), ("Q;P", seq(Q, P, N)[0]), ("blind", blind(P, Q, N, j_frame)[0])]:
        print(f"  {nmf:6s} {show_fam(f, N, nmf)}")
